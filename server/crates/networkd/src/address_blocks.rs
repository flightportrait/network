/// ISO alpha-2 of the state the address block belongs to, or None;
/// the smallest containing block wins.
pub fn state_of(hex: &str) -> Option<&'static str> {
    let address = u32::from_str_radix(hex, 16).ok()?;
    let mut best: Option<(u32, u32, &str)> = None;
    for &(first, last, state) in BLOCKS {
        if first > address {
            break;
        }
        if address <= last && best.is_none_or(|b| last - first < b.1 - b.0) {
            best = Some((first, last, state));
        }
    }
    best.map(|b| b.2)
}

#[cfg(test)]
mod tests {
    #[test]
    fn states() {
        assert_eq!(super::state_of("76cd62"), Some("SG"));
        assert_eq!(super::state_of("4ca123"), Some("IE"));
        assert_eq!(super::state_of("a1b2c3"), Some("US"));
        assert_eq!(super::state_of("000001"), None);
        assert_eq!(super::state_of("ffffff"), None);
        assert_eq!(super::state_of("06a12b"), Some("QA"));
        assert_eq!(super::state_of("7c0001"), Some("AU"));
        assert_eq!(super::state_of("3c6444"), Some("DE"));
    }
}
